export const ELEMENTS = ROWS.map((row, i) => ({
  sym: row[0],
  name: row[1],
  z: i + 1,
  density: row[2],
  hardness: row[3],
  form: row[4],
  body: row[5],
  pixels: pixelsOf(i + 1, row[4]),
}));

const BY = new Map(ELEMENTS.map((item) => [item.sym, item]));

export function element(sym) {
  return BY.get(sym);
}

function pixelsOf(z, form) {
  const gas = form === "gas";
  const cells = Array(16).fill(gas ? "." : "0");
  if (form === "flake") {
    for (let i = 0; i < 16; i += 2) cells[i] = "2";
  } else if (form === "liquid") {
    for (let i = 0; i < 4; i++) cells[i] = "1";
    for (let i = 12; i < 16; i++) cells[i] = "2";
  } else if (form === "wax") {
    for (const i of [5, 6, 9, 10]) cells[i] = "1";
  } else if (form === "crystal") {
    cells[1] = "1";
    cells[6] = "2";
    cells[11] = "1";
  } else if (form === "metal") {
    cells[0] = "1";
    cells[15] = "2";
  }
  const marks = gas ? [".", "0", "1"] : ["0", "1", "2"];
  let n = z;
  for (const slot of [2, 5, 8, 11, 14]) {
    cells[slot] = marks[n % 3];
    n = Math.floor(n / 3);
  }
  return cells.join("");
}
